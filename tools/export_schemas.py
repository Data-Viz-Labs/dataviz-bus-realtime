"""Generate the history schema artefacts from sim.history.SCHEMAS (the single source of truth):

- terraform/history_schema.json   Glue tables (Terraform reads it)
- docs/api/datasets.md            data dictionary for participants

    python tools/export_schemas.py
"""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from sim.history import PARTITION, SCHEMAS  # noqa: E402

TF_OUT = ROOT / "terraform" / "history_schema.json"
DOC_OUT = ROOT / "docs" / "api" / "datasets.md"

ABOUT = {
    "line_hourly": "One row per service hour, line and direction. Covers the whole history (years).",
    "stop_hourly": "One row per service hour and stop, all lines together. Covers the whole history.",
    "stop_calls": "One row each time a bus calls at a stop. Last days of history plus the live day.",
    "bus_positions": "Every bus every 30 seconds. Last days of history plus the live day.",
}


def terraform_schema() -> dict:
    return {
        table: {"partition": PARTITION[table], "columns": [{"name": n, "type": t, "comment": c} for n, t, c in cols]}
        for table, cols in SCHEMAS.items()
    }


def datasets_md() -> str:
    out = [
        "# Historical datasets",
        "",
        "<!-- generated by tools/export_schemas.py from sim/history.py; do not edit -->",
        "",
        "The history is a set of Parquet tables. Service hours are 06:00-23:59, local time",
        "(Europe/Madrid). Read them through the HTTP API (`/v1/history/...`, `/v1/sql`,",
        "`/v1/datasets/{table}/files` for direct Parquet downloads) or the MCP server",
        "(`run_sql`, `line_hourly`, ...). See [openapi.yaml](openapi.yaml) and [mcp.md](mcp.md).",
        "",
        "Every table is partitioned: always filter on the partition column in SQL",
        "(`WHERE month BETWEEN '2025-01' AND '2025-03'` or `WHERE dt = '2026-10-09'`), it is",
        "what keeps queries fast and within the scan limit.",
        "",
    ]
    for table, cols in SCHEMAS.items():
        part = PARTITION[table]
        fmt = "YYYY-MM" if part == "month" else "YYYY-MM-DD"
        out += [f"## `{table}`", "", ABOUT[table], "", f"Partition column: `{part}` (string, `{fmt}`).", "",
                "| Column | Type | Description |", "|---|---|---|"]
        out += [f"| `{n}` | {t} | {c} |" for n, t, c in cols]
        out.append("")
    out += [
        "## Example queries",
        "",
        "```sql",
        "-- Average rush-hour load per line in a quarter",
        "SELECT line_id, round(avg(avg_load), 3) AS load",
        "FROM line_hourly",
        "WHERE month BETWEEN '2025-01' AND '2025-03' AND hour IN (8, 18) AND day_of_week(date) <= 5",
        "GROUP BY line_id ORDER BY load DESC;",
        "",
        "-- Days with no service at all",
        "SELECT date, sum(trips) AS trips FROM line_hourly",
        "WHERE month BETWEEN '2024-01' AND '2026-12' GROUP BY date HAVING sum(trips) = 0 ORDER BY date;",
        "",
        "-- Unusual evening crowds at a stop",
        "SELECT date, hour, boardings FROM stop_hourly",
        "WHERE month >= '2025-01' AND stop_id = '72' AND hour >= 18 ORDER BY boardings DESC LIMIT 20;",
        "```",
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    TF_OUT.write_text(json.dumps(terraform_schema(), indent=2, ensure_ascii=False) + "\n")
    DOC_OUT.write_text(datasets_md())
