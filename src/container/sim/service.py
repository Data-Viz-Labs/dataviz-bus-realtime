"""Long-running simulator service (the Fargate task).

Runs the world in real time and publishes it:

- live/snapshot.json in the site bucket every few seconds (the map; behind CloudFront);
- MQTT messages per line on AWS IoT Core (students subscribe);
- the tracked lines' buses to an Amazon Location tracker;
- history rows (Parquet) in the data bucket, continuing the history generated by
  ``sim.backfill``; the scenario it generated also drives today's demand and events.

Configuration comes from the environment:

    SITE_BUCKET          bucket served by CloudFront            (required)
    DATA_BUCKET          private data bucket                    (required)
    TRACKER_NAME         Amazon Location tracker                (required unless TRACKED_LINES="")
    TRACKED_LINES        lines written to the tracker: ids, "all" or "" (none). Default "27"
    GEOFENCE_COLLECTION  stop geofences; when set, stop calls are written too (optional)
    MAP_KEY_NAME         Amazon Location API key for the map    (optional)
    API_URL              HTTP API base URL, advertised in live/config.json (optional)
    MQTT_ENDPOINT        AWS IoT Core data endpoint; empty disables MQTT
    MQTT_STATE_SECONDS   5     how often each line's state is published
    LINES_FILE           data/lines.yaml
    NETWORK_FILE         data/network.json (street geometry; optional)
    LINES                comma-separated subset of lines to simulate (default: all)
    TICK_SECONDS         5     simulation step
    SNAPSHOT_SECONDS     5     how often the map snapshot is written
    HEARTBEAT_SECONDS    120   max time between two tracker writes of a bus
    STATE_SECONDS        60    how often the world is saved for restarts
    HISTORY_SECONDS      600   how often history rows are written
    RESUME_MAX_MINUTES   15    older saved state is discarded on start-up
    TIMEZONE             Europe/Madrid (local time drives demand)
    SEED                 random seed (optional)
"""

from datetime import datetime, timedelta
import logging
import os
import signal
import time
from zoneinfo import ZoneInfo

import boto3

from sim.aws import DataStore, LocationPublisher, SiteStore, sync_geofences
from sim.config import build_world
from sim.history import LiveHistory
from sim.mqtt import MqttPublisher
from sim.scenario import Scenario

log = logging.getLogger("sim.service")


def env(name: str, default: str | None = None) -> str:
    value = os.environ.get(name, default)
    if value is None:
        raise SystemExit(f"missing required environment variable {name}")
    return value


def id_set(value: str) -> set[str]:
    return {x.strip() for x in value.split(",") if x.strip()}


class Every:
    """True once per ``seconds`` of simulated time."""

    def __init__(self, seconds: float):
        self.period, self.last = timedelta(seconds=seconds), None

    def due(self, now: datetime) -> bool:
        if self.last is None or now - self.last >= self.period:
            self.last = now
            return True
        return False


def load_story(data: DataStore, world) -> tuple[int | None, datetime | None]:
    """Apply the generated scenario (if any) to the world; return its seed and the history end."""
    raw = data.get_json(DataStore.SCENARIO)
    if raw and (world.conditions is None or world.conditions.seed != raw["seed"]):
        world.conditions = Scenario.from_json(raw, world.lines)
        log.info("scenario loaded")
    return (raw or {}).get("seed"), data.history_until()


def main() -> None:
    logging.basicConfig(level=env("LOG_LEVEL", "INFO"), format="%(asctime)s %(levelname)s %(name)s %(message)s")
    tz = ZoneInfo(env("TIMEZONE", "Europe/Madrid"))
    tick = float(env("TICK_SECONDS", "5"))
    seed = os.environ.get("SEED")
    world = build_world(
        env("LINES_FILE", "data/lines.yaml"), env("NETWORK_FILE", "data/network.json"),
        start=datetime.now(tz).replace(microsecond=0), seed=int(seed) if seed else None,
        only_lines=id_set(env("LINES", "")) or None,
    )

    location, s3 = boto3.client("location"), boto3.client("s3")
    site, data = SiteStore(s3, env("SITE_BUCKET")), DataStore(s3, env("DATA_BUCKET"))
    tracked = env("TRACKED_LINES", "27").strip()
    collection = os.environ.get("GEOFENCE_COLLECTION")
    tracker = None
    if tracked:
        lines = None if tracked == "all" else id_set(tracked) & set(world.lines)
        tracker = LocationPublisher(location, env("TRACKER_NAME"), float(env("HEARTBEAT_SECONDS", "120")),
                                    lines=lines, stop_calls=bool(collection))
        if collection:
            scope = world.lines if lines is None else {k: v for k, v in world.lines.items() if k in lines}
            log.info("geofences created: %d", sync_geofences(location, collection, scope))
    mqtt = None
    if endpoint := os.environ.get("MQTT_ENDPOINT"):
        mqtt = MqttPublisher(boto3.client("iot-data", endpoint_url=f"https://{endpoint}"), world.lines,
                             state_every_s=float(env("MQTT_STATE_SECONDS", "5")))

    key_name = os.environ.get("MAP_KEY_NAME")
    site.put_config(location.meta.region_name, location.describe_key(KeyName=key_name)["Key"] if key_name else None,
                    os.environ.get("API_URL"))
    _, until = load_story(data, world)
    if saved := data.load_state(timedelta(minutes=float(env("RESUME_MAX_MINUTES", "15")))):
        world.restore(saved)
        log.info("resumed saved state")
    history = LiveHistory(data.put, {b.bus_id: b.capacity for b in world.buses.values()})
    log.info("simulating %d lines, %d buses; tracker: %s; mqtt: %s", len(world.lines), len(world.buses),
             tracked or "off", "on" if mqtt else "off")

    stopping = False

    def stop(*_):
        nonlocal stopping
        stopping = True

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)

    snapshot_every = Every(float(env("SNAPSHOT_SECONDS", "5")))
    state_every = Every(float(env("STATE_SECONDS", "60")))
    history_every = Every(float(env("HISTORY_SECONDS", "600")))
    history_every.due(world.clock)  # first flush after a full period
    deadline = time.monotonic()
    while not stopping:
        result = world.step(tick)
        history.add(result)
        outputs = [("mqtt", mqtt), ("tracker", tracker)]
        if snapshot_every.due(result.time):
            outputs.append(("snapshot", site))
        for name, out in outputs:
            if out is None:
                continue
            try:
                out.put_snapshot(result) if out is site else out.publish(result)
            except Exception:  # keep simulating through transient AWS errors
                log.exception("%s publishing failed", name)
        try:
            if state_every.due(result.time):
                data.save_state(world)
                log.info("t=%s on_board=%d waiting=%d", f"{result.time:%H:%M:%S}",
                         sum(b.passengers for b in result.buses), sum(result.waiting.values()))
            if history_every.due(result.time):
                _, until = load_story(data, world)  # picks up a backfill that finished meanwhile
                log.info("history rows written: %d", history.flush(until, result.time))
        except Exception:
            log.exception("saving failed")
        deadline += tick
        time.sleep(max(0.0, deadline - time.monotonic()))
    data.save_state(world)
    history.flush(until, world.clock, final=True)
    log.info("state saved, stopping")


if __name__ == "__main__":
    main()
